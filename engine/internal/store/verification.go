package store

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/jackc/pgx/v5"
)

// Audit actions for ownership verification.
const (
	ActionVerifyTokenIssued   = "target.verify_token_issued"
	ActionVerified            = "target.verified"
	ActionVerificationFailed  = "target.verification_failed"
	ActionVerificationRevoked = "target.verification_revoked"
)

var (
	// ErrAlreadyVerified is returned when issuing a token for a target that
	// is already verified: replacing its token would break the published
	// record.
	ErrAlreadyVerified = errors.New("target already verified")
	// ErrTokenMismatch means the token is not the target's current one, or
	// it expired, so the verification attempt is stale.
	ErrTokenMismatch = errors.New("verification token is not current")
)

// The methods below are shared by the worker's Store and an Org (see scope
// in org.go). Through an Org, a target of another organization is
// ErrNotFound (or ErrTokenMismatch for MarkVerified), as if it did not
// exist.

// IssueVerificationToken stores a new token for an unverified target.
// Tokens are generated by package ownership; the store only keeps them.
func (sc scope) IssueVerificationToken(ctx context.Context, targetID, token string, expiresAt time.Time, actor string) error {
	if !isUUID(targetID) {
		return fmt.Errorf("issue verification token for %s: %w", targetID, ErrNotFound)
	}
	tx, err := sc.begin(ctx)
	if err != nil {
		return fmt.Errorf("issue verification token: %w", err)
	}
	defer tx.Rollback(ctx)

	var orgID, domain string
	var verified bool
	err = tx.QueryRow(ctx, `SELECT org_id::text, domain, verified_at IS NOT NULL FROM targets
		WHERE id = $1 AND ($2::uuid IS NULL OR org_id = $2::uuid) FOR UPDATE`,
		targetID, sc.orgParam()).Scan(&orgID, &domain, &verified)
	if errors.Is(err, pgx.ErrNoRows) {
		return fmt.Errorf("issue verification token for %s: %w", targetID, ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("issue verification token: %w", err)
	}
	if verified {
		return fmt.Errorf("issue verification token for %s: %w", domain, ErrAlreadyVerified)
	}
	if _, err := tx.Exec(ctx,
		"UPDATE targets SET verify_token = $2, verify_token_expires_at = $3 WHERE id = $1",
		targetID, token, expiresAt); err != nil {
		return fmt.Errorf("issue verification token for %s: %w", domain, err)
	}
	// The token itself is not logged: it is not secret once published, but
	// the audit log does not need it.
	if err := appendAudit(ctx, tx, AuditEntry{
		OrgID: orgID, Actor: actor, Action: ActionVerifyTokenIssued, Target: domain,
		Details: map[string]any{"expires_at": expiresAt.UTC()},
	}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("issue verification token: %w", err)
	}
	return nil
}

// MarkVerified records that the record holding token was found. It succeeds
// only if token is still the target's current, unexpired token, so a token
// replaced or expired in the meantime cannot verify the target.
func (sc scope) MarkVerified(ctx context.Context, targetID, token, actor string) error {
	if !isUUID(targetID) {
		return fmt.Errorf("mark %s verified: %w", targetID, ErrTokenMismatch)
	}
	tx, err := sc.begin(ctx)
	if err != nil {
		return fmt.Errorf("mark verified: %w", err)
	}
	defer tx.Rollback(ctx)

	var orgID, domain string
	err = tx.QueryRow(ctx, `
		UPDATE targets SET verified_at = now(), verify_checked_at = now(), verify_token_expires_at = NULL
		WHERE id = $1 AND ($3::uuid IS NULL OR org_id = $3::uuid)
		  AND verified_at IS NULL AND verify_token = $2 AND verify_token_expires_at > now()
		RETURNING org_id::text, domain`, targetID, token, sc.orgParam()).Scan(&orgID, &domain)
	if errors.Is(err, pgx.ErrNoRows) {
		return fmt.Errorf("mark %s verified: %w", targetID, ErrTokenMismatch)
	}
	if err != nil {
		return fmt.Errorf("mark %s verified: %w", targetID, err)
	}
	if err := appendAudit(ctx, tx, AuditEntry{OrgID: orgID, Actor: actor, Action: ActionVerified, Target: domain}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("mark verified: %w", err)
	}
	return nil
}

// TouchVerification records a successful re-check of a verified target.
func (sc scope) TouchVerification(ctx context.Context, targetID string) error {
	if !isUUID(targetID) {
		return fmt.Errorf("touch verification of %s: %w", targetID, ErrNotFound)
	}
	tx, err := sc.begin(ctx)
	if err != nil {
		return fmt.Errorf("touch verification of %s: %w", targetID, err)
	}
	defer tx.Rollback(ctx)
	tag, err := tx.Exec(ctx, `UPDATE targets SET verify_checked_at = now()
		WHERE id = $1 AND ($2::uuid IS NULL OR org_id = $2::uuid) AND verified_at IS NOT NULL`,
		targetID, sc.orgParam())
	if err != nil {
		return fmt.Errorf("touch verification of %s: %w", targetID, err)
	}
	if tag.RowsAffected() == 0 {
		return fmt.Errorf("touch verification of %s: %w", targetID, ErrNotFound)
	}
	return tx.Commit(ctx)
}

// RevokeVerification removes the verified status, for example because the
// record disappeared (the domain may have changed hands). The token is kept
// and gets a new deadline, so publishing the same record again and running
// verification restores the status.
func (sc scope) RevokeVerification(ctx context.Context, targetID, actor, reason string, retryWindow time.Duration) error {
	if !isUUID(targetID) {
		return fmt.Errorf("revoke verification of %s: %w", targetID, ErrNotFound)
	}
	tx, err := sc.begin(ctx)
	if err != nil {
		return fmt.Errorf("revoke verification: %w", err)
	}
	defer tx.Rollback(ctx)

	var orgID, domain string
	err = tx.QueryRow(ctx, `
		UPDATE targets SET verified_at = NULL, verify_checked_at = NULL,
			verify_token_expires_at = now() + make_interval(secs => $2)
		WHERE id = $1 AND ($3::uuid IS NULL OR org_id = $3::uuid) AND verified_at IS NOT NULL
		RETURNING org_id::text, domain`, targetID, retryWindow.Seconds(), sc.orgParam()).Scan(&orgID, &domain)
	if errors.Is(err, pgx.ErrNoRows) {
		return fmt.Errorf("revoke verification of %s: %w", targetID, ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("revoke verification of %s: %w", targetID, err)
	}
	if err := appendAudit(ctx, tx, AuditEntry{
		OrgID: orgID, Actor: actor, Action: ActionVerificationRevoked, Target: domain,
		Details: map[string]any{"reason": truncateRunes(reason, maxErrorChars)},
	}); err != nil {
		return err
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("revoke verification: %w", err)
	}
	return nil
}
